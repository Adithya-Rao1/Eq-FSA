from __future__ import annotations

# Sequential script for a single machine without Slurm. Runs the same jobs that slurm.campaign renders as sbatch scripts

import argparse
import json
import os
import shutil
import signal
import subprocess
import sys
import time
from dataclasses import asdict

from baselines.slurm import campaign
from baselines.slurm.campaign import Job, job_commands, job_layout
from baselines.slurm.launch import q

GPU_JOB_TYPES = ("smoke_test", "train")  # these get --nv; export and classical jobs are CPU only


def find_container_bin(explicit: str | None) -> str:
    found = shutil.which(explicit) if explicit else (shutil.which("apptainer") or shutil.which("singularity"))
    if not found:
        raise SystemExit(f"no container runtime found ({explicit or 'apptainer / singularity'}); install apptainer or pass --container-bin")
    return found


def done_marker(job: Job, scratch_root: str) -> str | None:
    export_dir, run_dir, _ = job_layout(job, scratch_root)
    if job.job_type == "export":
        return f"{export_dir}/split.json"  # written last, so its presence means a complete export
    if job.job_type in ("train", "classical"):
        return f"{run_dir}/metrics.json"
    return None  # smoke tests always run


def local_script(job: Job, scratch_root: str, repo_dir: str, epochs: int, extra_adapter_args: str, container_bin: str, cpus: int) -> str:
    _, run_dir, image = job_layout(job, scratch_root)
    sidecar = f"{image}.sha256"
    binds = [f"--bind {q(f'{scratch_root}:{scratch_root}')}", f"--bind {q(f'{repo_dir}:/repo:ro')}"]
    if os.path.exists(sidecar):
        binds.append(f"--bind {q(f'{sidecar}:/opt/image_digest.txt:ro')}")
    nv = "--nv" if job.job_type in GPU_JOB_TYPES else ""
    lines = [
        "#!/bin/bash",
        f"# local run of {job.run_name} ({job.phase}); generated by baselines.slurm.run_local",
        "set -euo pipefail",
        f"IMAGE={q(image)}",
        f"WORKDIR={q(run_dir)}",
        'mkdir -p "$WORKDIR"',
        'cd "$WORKDIR"',
        f"export OMP_NUM_THREADS={cpus}",
        "export SINGULARITYENV_PYTHONPATH=/repo/src",
        "export APPTAINERENV_PYTHONPATH=/repo/src",
        "sing() {",
        f"    {q(container_bin)} exec {nv} {' '.join(binds)} --pwd \"$WORKDIR\" \"$IMAGE\" \"$@\"",
        "}",
        "",
        *job_commands(job, scratch_root, epochs, extra_adapter_args),
    ]
    return "\n".join(lines) + "\n"


def _kill_group(proc: subprocess.Popen) -> None:
    for sig, wait in ((signal.SIGTERM, 30), (signal.SIGKILL, 10)):
        try:
            os.killpg(proc.pid, sig)
            proc.wait(timeout=wait)
            return
        except (ProcessLookupError, subprocess.TimeoutExpired):
            continue


def run_job(job: Job, script_path: str, log_path: str, timeout_s: float | None) -> tuple[str, int | None]:
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    with open(log_path, "a") as log:
        log.write(f"\n===== {time.strftime('%Y-%m-%d %H:%M:%S')} start {job.run_name} =====\n")
        log.flush()
        proc = subprocess.Popen(["bash", script_path], stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        try:
            code = proc.wait(timeout=timeout_s)
        except subprocess.TimeoutExpired:
            _kill_group(proc)
            return "timeout", None
        except KeyboardInterrupt:
            _kill_group(proc)
            raise
    return ("done" if code == 0 else "failed"), code


def select_jobs(phases: list[str], args: argparse.Namespace) -> list[Job]:
    jobs: list[Job] = []
    for phase in phases:
        jobs += campaign.expand_phase(
            phase, tuple(args.seeds), args.spice_file, args.ani1x_file, tuple(args.models) if args.models else None,
            tuple(args.datasets) if args.datasets else None, args.pilot,
        )
    if args.only:
        jobs = [j for j in jobs if j.job_type == "smoke_test" or j.dataset in args.only]
    return jobs


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Run campaign jobs one after another on this machine (no Slurm). Skips finished jobs; safe to restart.")
    p.add_argument("--phase", nargs="+", required=True, choices=list(campaign.PHASES), help="phases, run in the order given")
    p.add_argument("--scratch-root", required=True, help="dir with the .sif images, data/, exports/ and runs/ (e.g. $HOME/scratch)")
    p.add_argument("--repo-dir", default=None, help="repo checkout (default: <scratch-root>/Eq-FSA)")
    p.add_argument("--log-dir", default=None, help="job logs, scripts and results.jsonl (default: <scratch-root>/campaign/local)")
    p.add_argument("--epochs", type=int, default=1)
    p.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    p.add_argument("--models", nargs="+", default=None, help="ML models (or gaff2 / openff for phase3_classical)")
    p.add_argument("--datasets", nargs="+", default=None, choices=list(campaign.DATASET_FAMILIES))
    p.add_argument("--only", nargs="+", default=None, help="exact dataset ids to keep, e.g. rmd17:aspirin (smoke tests are always kept)")
    p.add_argument("--pilot", action="store_true", help="seed 0 and one dataset instance per model and family")
    p.add_argument("--spice-file", default=campaign.SPICE_FILENAME)
    p.add_argument("--ani1x-file", default=campaign.ANI1X_FILENAME)
    p.add_argument("--extra-adapter-args", default="", help="verbatim extra CLI text appended to the trainer command")
    p.add_argument("--container-bin", default=None, help="apptainer or singularity (default: whichever is on PATH)")
    p.add_argument("--cpus", type=int, default=os.cpu_count() or 4, help="OMP_NUM_THREADS inside jobs")
    p.add_argument("--job-timeout-hours", type=float, default=None)
    p.add_argument("--fail-fast", action="store_true", help="stop at the first failed job (default: keep going and summarize at the end)")
    p.add_argument("--dry-run", action="store_true", help="write the job scripts and print the plan; run nothing")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    scratch = args.scratch_root.rstrip("/")
    repo_dir = (args.repo_dir or f"{scratch}/Eq-FSA").rstrip("/")
    log_dir = (args.log_dir or f"{scratch}/campaign/local").rstrip("/")
    jobs = select_jobs(args.phase, args)
    if not jobs:
        print("[run_local] no jobs match the phase / model / dataset filters")
        return 1
    container_bin = None if args.dry_run else find_container_bin(args.container_bin)
    if not args.dry_run:
        missing = sorted({job_layout(j, scratch)[2] for j in jobs if not os.path.isfile(job_layout(j, scratch)[2])})
        if missing:
            print("[run_local] missing images:\n  " + "\n  ".join(missing), file=sys.stderr)
            return 2
    timeout_s = args.job_timeout_hours * 3600 if args.job_timeout_hours else None
    results_path = os.path.join(log_dir, "results.jsonl")
    os.makedirs(log_dir, exist_ok=True)
    print(f"[run_local] {len(jobs)} jobs; logs and scripts in {log_dir}")

    counts: dict[str, int] = {}
    failed: list[str] = []
    started = time.time()
    for n, job in enumerate(jobs, start=1):
        marker = done_marker(job, scratch)
        script_path = os.path.join(log_dir, job.phase, f"{job.run_name}.sh")
        log_path = os.path.join(log_dir, job.phase, f"{job.run_name}.log")
        os.makedirs(os.path.dirname(script_path), exist_ok=True)
        with open(script_path, "w") as f:
            f.write(local_script(job, scratch, repo_dir, args.epochs, args.extra_adapter_args, container_bin or "apptainer", args.cpus))
        t0 = time.time()
        if args.dry_run:
            status, code = "dry_run", None
        elif marker and os.path.exists(marker):
            status, code = "skipped", None
        else:
            try:
                status, code = run_job(job, script_path, log_path, timeout_s)
            except KeyboardInterrupt:
                print(f"\n[run_local] interrupted during {job.run_name}; rerun the same command to resume", file=sys.stderr)
                _record(results_path, job, "interrupted", None, time.time() - t0, log_path, script_path)
                return 130
        seconds = time.time() - t0
        counts[status] = counts.get(status, 0) + 1
        print(f"[run_local] [{n}/{len(jobs)}] {status:8s} {job.run_name}  ({seconds:.0f}s)" + (f"  log: {log_path}" if status in ("failed", "timeout") else ""))
        if not args.dry_run:
            _record(results_path, job, status, code, seconds, log_path, script_path)
        if status in ("failed", "timeout"):
            failed.append(job.run_name)
            if args.fail_fast:
                break
    print(f"[run_local] finished in {(time.time() - started) / 60:.1f} min: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    if failed:
        print("[run_local] FAILED:\n  " + "\n  ".join(failed), file=sys.stderr)
        return 1
    return 0


def _record(path: str, job: Job, status: str, code: int | None, seconds: float, log: str, script: str) -> None:
    row = {**asdict(job), "run_name": job.run_name, "status": status, "returncode": code, "seconds": round(seconds, 1), "log": log, "script": script,
           "finished_at": time.strftime("%Y-%m-%dT%H:%M:%S")}
    with open(path, "a") as f:
        f.write(json.dumps(row) + "\n")


if __name__ == "__main__":
    raise SystemExit(main())
